// Parity audit: our upstream /of operations vs the reference product's route table (plan-v5 §2.5).
// node:fs only. The mirror is PII: every subcommand reads only the keys it needs and prints only
// route methods/uris/names or key paths and JSON types, never a value from the page.
//
// Usage (from the repo root):
//   node scripts/parity-audit.mjs extract <mirror page.html>
//     Reads props.ziggy.routes from the page's <script data-page="app"> JSON and writes
//     docs/spec/parity/reference-routes.txt: one `METHODS uri name` line per `api/` route
//     (HEAD dropped, methods comma-joined, sorted by uri).
//   node scripts/parity-audit.mjs check <upstream-openapi.json> [--missing] [--have]
//     Compares the per-account lines of reference-routes.txt with the spec's /of/* operations.
//     An operation is `METHOD tail` with every {param} written as {}. A line is "have" only when
//     every method it advertises is served. --missing lists the missing lines; --have prints our
//     matched operations, sorted, on stdout (the baseline.txt format) and moves the report to stderr.
//     Exit 1 when an operation in docs/spec/parity/baseline.txt is missing from the spec (regression)
//     or when one of our operations, other than _of, matches no reference line (off-spec).
//   node scripts/parity-audit.mjs shapes <webhooks page.html> <fixtures dir>   (local only)
//     Compares key paths and JSON types of props.examplePayloads with <fixtures dir>/<event>.json.
//
// Dump the upstream spec with (in services/upstream, UPSTREAM_TOKEN = any 16+ chars):
//   python -c 'import json, app; print(json.dumps(app.app.openapi()))' > /tmp/up.json
// Regenerate the baseline (orchestrator only, after a wave merge, as its own commit):
//   node scripts/parity-audit.mjs check /tmp/up.json --have > docs/spec/parity/baseline.txt
//
// Self-check (manual): extract gives ~445 lines and 236 `api/{account` lines; a spec with one
// route renamed exits 1 (off-spec); a spec with one baseline operation removed exits 1
// (regression); a `PUT,PATCH` line served with PUT only is counted missing.
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';

const ROUTES_FILE = new URL('../docs/spec/parity/reference-routes.txt', import.meta.url);
const BASELINE_FILE = new URL('../docs/spec/parity/baseline.txt', import.meta.url);
const ACCOUNT = 'api/{account}/';
const PASSTHROUGH = '_of';

/**
 * Not counted (uri prefixes, after `api/`). Mirrors plan-v5 §8 "Out of scope" / "Excluded by the
 * inventory" and inventory section F; the inventory's cut rows must agree with this list.
 */
const OUT_OF_SCOPE = [
  'fansly/', // Fansly
  'smart-links', // Smart Links
  'smart-link-postbacks', // Smart Links postbacks
  '_internal/', // FansBot, mastra and their dashboard plumbing
  '_auth_app/', // dashboard plumbing
  'data-exports', // data exports
  'fan-summary-categories', // AI features
  'ai-voice-messages', // AI features
  '{account}/fans/{fan_id}/summary', // AI features
  'webhooks/coingate', // billing: payment-provider callback
  'webhooks/vatstack', // billing: payment-provider callback
  'usage/credits', // billing: credit metering
];

const die = (msg) => {
  console.error(`parity-audit: ${msg}`);
  process.exit(2);
};

/** The Inertia page object from a mirror page; nothing from it is printed. */
function pageProps(file) {
  const html = readFileSync(file, 'utf8');
  const m = html.match(/<script data-page="app"[^>]*>([\s\S]*?)<\/script>/);
  if (!m) die(`${file}: no <script data-page="app"> block`);
  try {
    return JSON.parse(m[1]).props ?? {};
  } catch {
    die(`${file}: the data-page block is not JSON`);
  }
}

const norm = (tail) => tail.replace(/\{[^}]*\}/g, '{}');
const outOfScope = (uri) => OUT_OF_SCOPE.some((p) => uri.slice('api/'.length).startsWith(p));
const isPassthrough = (tail) => tail === PASSTHROUGH || tail.startsWith(`${PASSTHROUGH}/`);

function extract(page) {
  const routes = pageProps(page).ziggy?.routes;
  if (!routes || typeof routes !== 'object') die(`${page}: no props.ziggy.routes`);
  const lines = Object.entries(routes)
    .filter(([, r]) => typeof r?.uri === 'string' && r.uri.startsWith('api/'))
    .map(([name, r]) => ({ uri: r.uri, name, methods: r.methods.filter((x) => x !== 'HEAD').join(',') }))
    .sort((a, b) => (a.uri < b.uri ? -1 : a.uri > b.uri ? 1 : a.methods < b.methods ? -1 : 1))
    .map((r) => `${r.methods} ${r.uri} ${r.name}`);
  const source = page.split('/').pop();
  const header = `# Reference route table: props.ziggy.routes under api/, from mirror page ${source}, extracted ${new Date().toISOString().slice(0, 10)}.\n# Format: METHODS uri name (HEAD dropped). Generated by scripts/parity-audit.mjs extract; do not edit.\n`;
  writeFileSync(ROUTES_FILE, `${header}${lines.join('\n')}\n`);
  console.log(`wrote ${lines.length} routes (${lines.filter((l) => l.includes(` ${ACCOUNT}`)).length} per-account) to docs/spec/parity/reference-routes.txt`);
}

const readLines = (file) =>
  readFileSync(file, 'utf8')
    .split('\n')
    .map((l) => l.trim())
    .filter((l) => l && !l.startsWith('#'));

function check(specFile, flags) {
  const spec = JSON.parse(readFileSync(specFile, 'utf8'));
  const ours = new Set();
  for (const [path, item] of Object.entries(spec.paths ?? {})) {
    if (!path.startsWith('/of/')) continue;
    for (const method of Object.keys(item)) {
      const m = method.toUpperCase();
      if (['GET', 'POST', 'PUT', 'PATCH', 'DELETE', 'OPTIONS'].includes(m)) ours.add(`${m} ${norm(path.slice(4))}`);
    }
  }

  const theirs = new Set();
  const groups = new Map();
  let team = 0;
  let notCounted = 0;
  const missing = [];
  for (const line of readLines(ROUTES_FILE)) {
    const [methods, uri] = line.split(' ');
    if (!uri.startsWith(ACCOUNT)) {
      if (!outOfScope(uri)) team++;
      continue;
    }
    const tail = uri.slice(ACCOUNT.length);
    const ops = methods.split(',').map((m) => `${m} ${norm(tail)}`);
    ops.forEach((op) => theirs.add(op));
    if (isPassthrough(tail) || outOfScope(uri)) {
      notCounted++;
      continue;
    }
    const group = tail.split('/')[0];
    const g = groups.get(group) ?? { have: 0, total: 0 };
    g.total++;
    if (ops.every((op) => ours.has(op))) g.have++;
    else missing.push(`${methods} ${tail}  (not served: ${ops.filter((op) => !ours.has(op)).map((op) => op.split(' ')[0]).join(',')})`);
    groups.set(group, g);
  }

  const out = flags.has('--have') ? console.error : console.log;
  let have = 0;
  let total = 0;
  for (const [group, g] of [...groups].sort()) {
    out(`${group} ${g.have}/${g.total}`);
    have += g.have;
    total += g.total;
  }
  out(`total ${have}/${total} per-account lines have (not counted: ${PASSTHROUGH}/{path?} and out-of-scope, ${notCounted} lines)`);
  out(`team-level: ${team} in-scope lines (informational, not gated; see the inventory, section B)`);
  if (flags.has('--missing')) missing.forEach((l) => out(`missing: ${l}`));

  let fail = false;
  const matched = [...ours].filter((op) => !isPassthrough(op.split(' ')[1])).sort();
  for (const op of matched.filter((op) => !theirs.has(op))) {
    console.error(`OFF-SPEC: ${op} (no reference line has this method and path; rename it, plan-v5 §1.1)`);
    fail = true;
  }
  const baseline = existsSync(BASELINE_FILE) ? readLines(BASELINE_FILE) : [];
  for (const op of baseline.filter((op) => !ours.has(op))) {
    console.error(`REGRESSION: ${op} is in docs/spec/parity/baseline.txt but missing from the spec`);
    fail = true;
  }
  if (flags.has('--have')) matched.filter((op) => theirs.has(op)).forEach((op) => console.log(op));
  if (fail) {
    console.error('parity-audit: FAIL');
    process.exit(1);
  }
}

/** key path -> JSON type, arrays as `[]`, every node included. */
function shape(value, path = '$', acc = new Map()) {
  const type = value === null ? 'null' : Array.isArray(value) ? 'array' : typeof value;
  const prev = acc.get(path);
  acc.set(path, prev ? [...new Set([...prev.split('|'), type])].sort().join('|') : type);
  if (type === 'array') value.forEach((v) => shape(v, `${path}[]`, acc));
  else if (type === 'object') for (const k of Object.keys(value)) shape(value[k], `${path}.${k}`, acc);
  return acc;
}

function shapes(page, dir) {
  const examples = pageProps(page).examplePayloads;
  if (!examples || typeof examples !== 'object') die(`${page}: no props.examplePayloads`);
  const entries = Array.isArray(examples) ? examples.map((e, i) => [e?.event ?? String(i), e]) : Object.entries(examples);
  if (!existsSync(dir)) {
    console.log(`fixtures dir ${dir} does not exist (P1b creates tests/fixtures/payloads); ${entries.length} reference events, nothing compared`);
    return;
  }
  const fixtures = new Set(readdirSync(dir).filter((f) => f.endsWith('.json')).map((f) => f.slice(0, -5)));
  let compared = 0;
  let bad = 0;
  const noFixture = [];
  for (const [event, example] of entries) {
    if (!fixtures.has(event)) {
      noFixture.push(event);
      continue;
    }
    fixtures.delete(event);
    compared++;
    const ref = shape(example);
    const fix = shape(JSON.parse(readFileSync(`${dir}/${event}.json`, 'utf8')));
    const diffs = [];
    for (const [p, t] of ref) {
      if (!fix.has(p)) diffs.push(`  only in reference: ${p} (${t})`);
      else if (fix.get(p) !== t) diffs.push(`  type differs: ${p} (reference ${t}, fixture ${fix.get(p)})`);
    }
    for (const [p, t] of fix) if (!ref.has(p)) diffs.push(`  only in fixture: ${p} (${t})`);
    if (diffs.length) {
      bad++;
      console.log(`${event}: ${diffs.length} difference(s)\n${diffs.join('\n')}`);
    } else console.log(`${event}: ok`);
  }
  for (const f of [...fixtures].sort()) console.log(`${f}: fixture has no reference example (our extension?)`);
  console.log(`compared ${compared}, differing ${bad}; ${noFixture.length} reference events have no fixture${compared ? '' : ` (dir ${dir} has no matching <event>.json)`}`);
  if (bad) process.exit(1);
}

const [cmd, ...args] = process.argv.slice(2);
const files = args.filter((a) => !a.startsWith('--'));
if (cmd === 'extract' && files.length === 1) extract(files[0]);
else if (cmd === 'check' && files.length === 1) check(files[0], new Set(args.filter((a) => a.startsWith('--'))));
else if (cmd === 'shapes' && files.length === 2) shapes(files[0], files[1]);
else die('usage: extract <page.html> | check <openapi.json> [--missing] [--have] | shapes <webhooks.html> <fixtures dir>');
